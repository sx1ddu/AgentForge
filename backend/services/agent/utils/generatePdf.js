import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margin: 50,
        info: {
          Author: "AgentForge",
          Title: data.title || "Generated Document",
          Creator: "AgentForge AI",
        },
      });

      const chunks = [];

      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", (err) => reject(err));

      // Title
      doc
        .fontSize(24)
        .fillColor("#111827")
        .text(data.title || "Untitled Document", {
          align: "center",
        });

      if (data.subtitle) {
        doc.moveDown(0.5);
        doc
          .fontSize(12)
          .fillColor("#6B7280")
          .text(data.subtitle, {
            align: "center",
          });
      }

      doc.moveDown(2);

      const sections = Array.isArray(data.sections) ? data.sections : [];

      sections.forEach((s) => {
        if (s.heading) {
          doc
            .fontSize(16)
            .fillColor("#1F2937")
            .text(s.heading);
          doc.moveDown(0.4);
        }

        const points = Array.isArray(s.points) ? s.points : [];
        points.forEach((p) => {
          doc
            .fontSize(11)
            .fillColor("#374151")
            .text(`• ${p}`, {
              lineGap: 4,
            });
        });

        doc.moveDown(1);
      });

      doc.moveDown(2);
      doc
        .fontSize(9)
        .fillColor("#9CA3AF")
        .text("Generated by AgentForge AI Platform", {
          align: "center",
        });

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
};
