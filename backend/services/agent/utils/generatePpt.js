import pptxgen from "pptxgenjs";

const COLORS = {
  primary: "#2563EB",
  secondary: "#1E293B",
  text: "#334155",
  light: "#F8FAFC",
  border: "#E2E8F0",
  white: "#FFFFFF",
  muted: "#64748B",
};

export const generatePpt = async (data) => {
  const ppt = new pptxgen();

  ppt.layout = "LAYOUT_WIDE";
  ppt.author = "AgentForge";
  ppt.title = data.title || "Presentation";
  ppt.subject = data.subtitle || data.title || "Presentation";
  ppt.company = "AgentForge AI";
  ppt.lang = "en-US";
  ppt.theme = {
    headFontFace: "Arial",
    bodyFontFace: "Arial",
  };

  addCover(ppt, data);

  const slides = Array.isArray(data.slides) ? data.slides : [];
  slides.forEach((s, i) => {
    addContentSlide(ppt, s.title || `Slide ${i + 1}`, s.points || [], i + 1, slides.length);
  });

  addThankYou(ppt);
  return ppt;
};

const addCover = (ppt, data) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.primary };

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.18,
    fill: { color: "60A5FA" },
    line: { color: "60A5FA" },
  });

  slide.addText(data.title || "AgentForge Presentation", {
    x: 0.7,
    y: 1.7,
    w: 12,
    h: 0.8,
    align: "center",
    color: COLORS.white,
    bold: true,
    fontSize: 28,
  });

  if (data.subtitle) {
    slide.addText(data.subtitle, {
      x: 1,
      y: 2.8,
      w: 11.5,
      h: 0.4,
      align: "center",
      color: "DBEAFE",
      fontSize: 15,
    });
  }

  slide.addText("Generated by AgentForge AI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "center",
    color: "BFDBFE",
    fontSize: 10,
  });
};

const addContentSlide = (ppt, title, points, page, total) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.white };

  slide.addText(title, {
    x: 0.6,
    y: 0.35,
    w: 10,
    h: 0.4,
    color: COLORS.primary,
    bold: true,
    fontSize: 24,
  });

  slide.addShape(ppt.ShapeType.line, {
    x: 0.6,
    y: 0.85,
    w: 12,
    h: 0,
    line: { color: COLORS.border, width: 1.2 },
  });

  const visiblePoints = Array.isArray(points) ? points.slice(0, 6) : [];

  visiblePoints.forEach((point, index) => {
    const y = 1.2 + index * 0.8;

    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.7,
      y,
      w: 12,
      h: 0.6,
      fill: { color: index % 2 ? "F8FAFC" : "EFF6FF" },
      line: { color: COLORS.border },
      radius: 0.08,
    });

    slide.addText(String(point), {
      x: 1.0,
      y: y + 0.1,
      w: 11.4,
      h: 0.4,
      fontSize: 14,
      color: COLORS.text,
      fit: "shrink",
    });
  });

  slide.addText(`${page}/${total}`, {
    x: 12.1,
    y: 6.9,
    w: 0.8,
    h: 0.2,
    fontSize: 10,
    color: COLORS.muted,
    align: "right",
  });

  slide.addText("AgentForge AI", {
    x: 0.6,
    y: 6.9,
    w: 2,
    h: 0.2,
    fontSize: 10,
    color: COLORS.muted,
  });
};

const addThankYou = (ppt) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.secondary };

  slide.addText("Thank You", {
    x: 0,
    y: 2.5,
    w: 13.33,
    h: 0.8,
    align: "center",
    color: COLORS.white,
    fontSize: 34,
    bold: true,
  });

  slide.addText("Generated by AgentForge AI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "center",
    color: "94A3B8",
    fontSize: 10,
  });
};
